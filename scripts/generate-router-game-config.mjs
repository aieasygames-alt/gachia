import { readFile, writeFile } from 'node:fs/promises';

const sourcePath = new URL('../packages/core/deployments.ts', import.meta.url);
const outputPath = new URL('../apps/router/src/generated-game-deployments.ts', import.meta.url);
const source = await readFile(sourcePath, 'utf8');
const entries = [...source.matchAll(/(?:'([^']+)'|([a-z0-9-]+)):\s*\{([\s\S]*?)\n\s*\},/g)]
  .map(([, quotedId, plainId, body]) => ({ id: quotedId ?? plainId, body }))
  .filter(({ body }) => /deployment:\s*'game'/.test(body) && /status:\s*'live'/.test(body));

const deployments = entries.map(({ id, body }) => {
  const worker = body.match(/worker:\s*'([^']+)'/)?.[1];
  const assetPrefix = body.match(/assetPrefix:\s*'([^']+)'/)?.[1];
  const sitemapPath = body.match(/sitemapPath:\s*'([^']+)'/)?.[1];
  if (!worker || !assetPrefix || !sitemapPath) throw new Error(`Incomplete live deployment: ${id}`);
  const envKey = id.toUpperCase().replaceAll('-', '_');
  return { id, worker, assetPrefix, sitemapPath, binding: `${envKey}_SITE`, enabled: `${envKey}_ENABLED` };
});

const content = `// Generated by scripts/generate-router-game-config.mjs. Do not edit manually.\n\nexport type GeneratedGameDeployment = {\n  id: string;\n  worker: string;\n  assetPrefix: string;\n  sitemapPath: string;\n  binding: string;\n  enabled: string;\n};\n\nexport const GENERATED_GAME_DEPLOYMENTS = ${JSON.stringify(deployments, null, 2)} as const satisfies readonly GeneratedGameDeployment[];\n`;
const current = await readFile(outputPath, 'utf8').catch(() => '');
if (current !== content) await writeFile(outputPath, content);
console.log(`Generated ${deployments.length} live Router game deployment(s).`);
