import { pathToFileURL } from 'node:url';
import ts from 'typescript';
import { readRouterInput, writeRouterOutput, routerInputLimit } from './router-config-files.mjs';

export function renderRouterConfig(source) {
  if (typeof source !== 'string' || Buffer.byteLength(source) > 1024 * 1024) throw new Error('Deployment source exceeds input budget');
  const tree = ts.createSourceFile('deployments.ts', source, ts.ScriptTarget.Latest, true);
  if (tree.parseDiagnostics.length) throw new Error('Invalid deployment source syntax');
  const declarations = tree.statements.filter(ts.isVariableStatement)
    .flatMap((statement) => [...statement.declarationList.declarations])
    .filter((declaration) => ts.isIdentifier(declaration.name) && declaration.name.text === 'GAME_DEPLOYMENTS');
  if (declarations.length !== 1) throw new Error('Expected exactly one GAME_DEPLOYMENTS declaration');
  const unwrap = (node) => {
    while (node && (ts.isAsExpression(node) || ts.isSatisfiesExpression(node) || ts.isParenthesizedExpression(node))) node = node.expression;
    return node;
  };
  const object = (node) => {
    node = unwrap(node);
    if (!node || !ts.isObjectLiteralExpression(node)) throw new Error('Expected static deployment object');
    if (node.properties.length > 256) throw new Error('Deployment object exceeds property budget');
    const values = new Map();
    for (const property of node.properties) {
      if (!ts.isPropertyAssignment(property) || !(ts.isIdentifier(property.name) || ts.isStringLiteral(property.name))) throw new Error('Unsupported dynamic deployment property');
      const key = property.name.text;
      if (values.has(key)) throw new Error(`Duplicate deployment key: ${key}`);
      values.set(key, property.initializer);
    }
    return values;
  };
  const deployments = [];
  const bindings = new Set();
  for (const [id, node] of object(declarations[0].initializer)) {
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(id)) throw new Error('Invalid deployment ID');
    const fields = object(node); const values = Object.create(null);
    for (const [key, value] of fields) {
      if (!['deployment', 'worker', 'assetPrefix', 'sitemapPath', 'status'].includes(key)) throw new Error(`Unknown deployment field: ${id}.${key}`);
      if (!ts.isStringLiteral(value)) throw new Error(`Unsupported nonliteral deployment field: ${id}.${key}`);
      values[key] = value.text;
    }
    const { deployment, worker, assetPrefix, sitemapPath, status } = values;
    if (!['main', 'game'].includes(deployment) || !['draft', 'preview', 'live', 'maintenance', 'retired'].includes(status) ||
      typeof worker !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(worker)) throw new Error(`Incomplete or invalid Router deployment: ${id}`);
    if (deployment !== 'game' || !['preview', 'live'].includes(status)) continue;
    if (assetPrefix !== `/_games/${id}` || sitemapPath !== `/sitemaps/${id}/index.xml`) throw new Error(`Incomplete or invalid Router deployment paths: ${id}`);
    const envKey = id.toUpperCase().replaceAll('-', '_'); const binding = `${envKey}_SITE`;
    if (bindings.has(binding)) throw new Error('Duplicate Router binding');
    bindings.add(binding);
    deployments.push({ id, worker, assetPrefix, sitemapPath, status, binding, enabled: `${envKey}_ENABLED` });
  }

const content = `// Generated by scripts/generate-router-game-config.mjs. Do not edit manually.\n\nexport type GeneratedGameDeployment = {\n  id: string;\n  worker: string;\n  assetPrefix: string;\n  sitemapPath: string;\n  status: 'preview' | 'live';\n  binding: string;\n  enabled: string;\n};\n\nexport const GENERATED_GAME_DEPLOYMENTS = ${JSON.stringify(deployments, null, 2)} as const satisfies readonly GeneratedGameDeployment[];\n`;
return { content, count: deployments.length };
}

export async function generateRouterConfig({ check = false,
  sourcePath = new URL('../packages/core/deployments.ts', import.meta.url),
  outputPath = new URL('../apps/router/src/generated-game-deployments.ts', import.meta.url) } = {}) {
  const source = await readRouterInput(sourcePath);
  const { content, count } = renderRouterConfig(source.text);
  const current = await readRouterInput(outputPath, { allowMissing: true });
  if ((await readRouterInput(sourcePath)).digest !== source.digest) throw new Error('Router source changed during observation');
  const consistent = current?.text === content;
  if (!check && !consistent) await writeRouterOutput(outputPath, content, current);
  return { count, consistent, mode: check ? 'read_only_check' : 'generate', written: !check && !consistent,
    inputs: { source: { digest: source.digest, bytes: source.bytes }, output: current ? { digest: current.digest, bytes: current.bytes } : { status: 'missing' } },
    limits: { maxBytesPerFile: routerInputLimit, hardTimeLimit: false },
    observation: 'bounded_same_read_digest_not_atomic_or_OS_isolation' };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check')) throw new Error('Usage: generate-router-game-config.mjs [--check]');
  const result = await generateRouterConfig({ check: args.includes('--check') });
  if (result.mode === 'read_only_check' && !result.consistent) {
    console.error('Router generated configuration is missing or stale; no files changed.'); process.exitCode = 1;
  } else console.log(`${result.mode === 'read_only_check' ? 'Checked' : 'Generated'} ${result.count} Router game deployment(s).`);
}
